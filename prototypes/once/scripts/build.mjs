/*
 * Builds the Once prototype pages: src/ → dist/.
 *
 * Every {{BSB:…}} placeholder is replaced with text from data/verses.json, so
 * no verse in a page is typed by hand. A placeholder that does not resolve, a
 * fragment that is not a substring of its verse, or any leftover {{…}} fails
 * the build.
 *
 * Run: node prototypes/once/scripts/build.mjs
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { KIT_READINGS, PLACEHOLDER, parseRef } from "./refs.mjs";

const SRC = new URL("../src/", import.meta.url);
const DIST = new URL("../dist/", import.meta.url);
const { verses, john } = JSON.parse(readFileSync(new URL("../data/verses.json", import.meta.url), "utf8"));

const count = (s, ch) => s.split(ch).length - 1;

/*
 * A verse lifted out of a speech can open or close a quotation that belongs
 * to the verses around it (Mark 1:15 opens with “, Matthew 25:46 closes with
 * ”). A dangling mark reads as a typo, so an unmatched outer double quote is
 * dropped. Nothing else in the text is touched.
 */
function trimOuterQuotes(text) {
	let t = text;
	if (t.startsWith("“") && count(t, "“") > count(t, "”")) t = t.slice(1);
	if (t.endsWith("”") && count(t, "”") > count(t, "“")) t = t.slice(0, -1);
	return t;
}

function render(ref, fragment, file) {
	const key = ref.trim();
	const parts = verses[key];
	if (!parts) throw new Error(`${file}: "${key}" is not in verses.json — run extract-verses.mjs`);
	const full = parts.join(" ");
	if (fragment !== undefined) {
		if (!full.includes(fragment)) {
			throw new Error(`${file}: fragment is not in ${key}: "${fragment}"`);
		}
		return fragment;
	}
	return trimOuterQuotes(full);
}

const escapeHtml = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escapeJsString = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

mkdirSync(DIST, { recursive: true });

let total = 0;
for (const file of readdirSync(SRC)) {
	const ext = file.match(/\.(html|js|css)$/)?.[1];
	if (!ext) continue;
	let text = readFileSync(new URL(file, SRC), "utf8");
	text = text.replace(PLACEHOLDER, (_, ref, fragment) => {
		total++;
		const out = render(ref, fragment, file);
		return ext === "js" ? escapeJsString(out) : escapeHtml(out);
	});
	text = text.replace(/\/\* KIT_READINGS \*\/ \[\]/g, () => JSON.stringify(KIT_READINGS));
	const leftover = text.match(/\{\{[^}]*\}\}|\[\[BSB:[^\]]*\]\]/);
	if (leftover) throw new Error(`${file}: unresolved placeholder ${leftover[0]}`);
	writeFileSync(new URL(file, DIST), text);
}

/*
 * The whole Gospel of John as a script that sets one global, so it can be
 * loaded from a file:// copy as well as from the published artifact (where a
 * fetch of a JSON file would also work, but a local file would not).
 */
const readings = KIT_READINGS.map(({ ref, title }) => {
	const r = parseRef(ref);
	return { ref, title, chapter: r.chapter, from: r.from, to: r.to };
});
writeFileSync(
	new URL("john-data.js", DIST),
	`/* Gospel of John, Berean Standard Bible (public domain). Generated by build.mjs. */\nwindow.ONCE_JOHN = ${JSON.stringify({ readings, chapters: john })};\n`,
);

console.log(`✓ built dist/ — ${total} scripture placeholders substituted`);
