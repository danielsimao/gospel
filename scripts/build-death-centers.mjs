/* Cover this share of world deaths; the tail is renormalised across the rest. */
const COVERAGE = 0.92;

const byDeaths = [...countries].sort((a, b) => b.deaths - a.deaths);
const world = byDeaths.reduce((s, c) => s + c.deaths, 0);

const picked = [];
let running = 0;
for (const c of byDeaths) {
  if (running / world >= COVERAGE) break;
  picked.push(c);
  running += c.deaths;
}

// Every curated country must survive the cut, or a hand-picked point vanishes.
for (const name of Object.keys(CURATED)) {
  if (!picked.some((c) => c.name === name)) {
    const found = byDeaths.find((c) => c.name === name);
    if (!found) throw new Error(`curated country not in source data: ${name}`);
    picked.push(found);
    running += found.deaths;
  }
}

const rows = [];
for (const c of picked) {
  const points = CURATED[c.name] ?? [[c.capital, c.lng, c.lat]];
  for (const [place, lng, lat] of points) {
    if (typeof lng !== "number" || typeof lat !== "number") {
      throw new Error(`no coordinates for ${c.name} (${place})`);
    }
    rows.push({ place, lng, lat, share: c.deaths / points.length / running });
  }
}

const sum = rows.reduce((s, r) => s + r.share, 0);
if (Math.abs(sum - 1) > 1e-9) throw new Error(`shares sum to ${sum}, not 1`);
rows.sort((a, b) => b.share - a.share);

const body = rows
  .map((r) => `  [${r.lng}, ${r.lat}, ${r.share.toFixed(6)}], // ${r.place}`)
  .join("\n");
writeFileSync(new URL("../src/components/eternity/death-centers.generated.ts", import.meta.url),
  `// GENERATED by scripts/build-death-centers.mjs — do not edit by hand.\n` +
  `// Source: docs/data/deaths-by-country.json (see its header for provenance).\n` +
  `// ${rows.length} points covering ${(100 * running / world).toFixed(1)}% of world deaths.\n` +
  `\n/** [longitude, latitude, share of world deaths]. Shares sum to 1. */\n` +
  `export const DEATH_CENTERS: readonly (readonly [number, number, number])[] = [\n${body}\n];\n`);

console.log(`${rows.length} points, ${picked.length} countries, ${(100 * running / world).toFixed(1)}% of world deaths`);
